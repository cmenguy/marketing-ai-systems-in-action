"""Listing 6.4 - Building each localized, audience-specific variant and checking it fits.

One campaign fans into a grid of variants, customized on two axes at once:
  - AUDIENCE: the headline is framed for the segment (loyalty leads with the
    product; lapsed leads with what changed), the same segment framing chapter 5
    used.
  - LOCALE: the headline is written per market, and the conditioning grounds the
    hero in the real product (listing 6.2) so every variant shows the actual
    Cascade.
Each variant is then checked: translated text does not fit the same box, so
German overflows and is held, and RTL locales flip the layout. `expand_campaign`
produces the whole audience-by-locale grid (figure 6.6). On-image text is
composited in the licensed font, never generated by the model.
"""
from __future__ import annotations

from dataclasses import dataclass

from C01_Menguy_MarketingAISystems import VisualBrandKit, northpeak_kit
from C02_Menguy_MarketingAISystems import build_request, Conditioning

AUDIENCE_FRAME = {
    "loyalty": "Lead with the product; the reader already trusts the brand.",
    "lapsed":  "Lead with what changed; give a reason to look again.",
}
RTL_LOCALES = {"ar", "he", "fa", "ur"}


@dataclass(frozen=True)
class Campaign:
    brief: str
    product: str          # product code into the kit
    kit: VisualBrandKit
    slot_width: int       # headline slot width, in px
    style_refs: tuple = ()


@dataclass(frozen=True)
class Variant:
    audience: str
    locale: str
    headline: str
    conditioning: Conditioning
    rtl: bool
    fits: bool


def variant_fits(text, box_width, text_width, safe_frac=0.9):
    return text_width(text) <= box_width * safe_frac      # leave a margin


def build_variant(campaign, audience, locale, headlines, text_width):
    req = build_request(
        f"{campaign.brief}. {AUDIENCE_FRAME[audience]}",   # audience framing
        campaign.kit, product_code=campaign.product,       # grounds the hero
        style_refs=campaign.style_refs)
    headline = headlines[(audience, locale)]               # per audience + locale
    return Variant(audience, locale, headline, req,
                   rtl=locale in RTL_LOCALES,
                   fits=variant_fits(headline, campaign.slot_width, text_width))


def expand_campaign(campaign, audiences, locales, headlines, text_width):
    return [build_variant(campaign, a, l, headlines, text_width)
            for a in audiences for l in locales]           # the F06 grid


def _px_width(text, per_char=11):
    """A real renderer measures the string in the licensed font; ~11px/char here."""
    return len(text) * per_char


HEADLINES = {
    ("loyalty", "en"): "Members get first access",
    ("loyalty", "de"): "Mitglieder erhalten zuerst Zugang zur Kollektion",
    ("loyalty", "ar"): "الأعضاء يحصلون على وصول مبكر",
    ("lapsed", "en"): "See what's new this spring",
    ("lapsed", "de"): "Sehen Sie, was diesen Frühling neu ist",
    ("lapsed", "ar"): "اكتشف الجديد هذا الربيع",
}


if __name__ == "__main__":
    kit = northpeak_kit()
    campaign = Campaign("The Cascade shell on a wet trail, hero shot",
                        product="cascade", kit=kit, slot_width=460)
    variants = expand_campaign(campaign, ["loyalty", "lapsed"],
                               ["en", "de", "ar"], HEADLINES, _px_width)
    for v in variants:
        flag = "OK  " if v.fits else "HELD"   # overflow -> held for a human
        print(f"  [{flag}] {v.audience:8} {v.locale}  rtl={v.rtl!s:5}  "
              f"grounded_on={v.conditioning.product_reference is not None}  "
              f"\"{v.headline[:38]}\"")
    print("held for overflow:",
          [f"{v.audience}/{v.locale}" for v in variants if not v.fits])
